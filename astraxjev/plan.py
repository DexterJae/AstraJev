"""Task plans as data.

The first version of this project hard-coded PickToBasket: a fixed eight-phase
enum, hand-written tolerances, and an if-else chain mapping each phase to a
waypoint. The routing mechanism on top of that was general, but what it routed
over was not -- a new task meant writing a new state machine, which means the
scaffold, not the models, was doing the work.

This module replaces the hard-coded machine with three pieces:

  GoalKind   a small, deliberately task-agnostic vocabulary of waypoint
             primitives. This is the only part that stays fixed, and it is
             fixed the way "move to a pose" is fixed, not the way
             "PickToBasket has seven phases" is fixed.

  Subgoal    one step of a plan: which primitive, against which scene
             reference, with what tolerance and whether it needs pixels. The
             routing decision (`jev_owns`) reads exactly these two fields, so
             it works unchanged on a plan it has never seen.

  TaskPlan   an ordered list of subgoals, *generated by Astra-Global once per
             episode* rather than written by hand.

Tolerances are then calibrated against quantities the environment actually
declares (see `calibrate`), so the numbers that decide who does what are
measured rather than chosen.
"""

from __future__ import annotations

import enum
from dataclasses import dataclass, field, replace
from typing import Any, Iterable, Optional

import numpy as np

from .types import GRIPPER_CLOSED, GRIPPER_OPEN, Waypoint


class GoalKind(enum.Enum):
    """The waypoint vocabulary.

    Every entry is a generic spatial relation, not a task step. "Stand off from
    a thing", "contact a thing", "withdraw", "go above a thing", "swing about a
    hinge" describe shelf picking, floor picking, board-to-board transfer and
    door opening alike.
    """

    STANDOFF = "standoff"  # out in front of a reference, along its normal
    CONTACT = "contact"  # at the reference, inset by the finger depth
    WITHDRAW = "withdraw"  # back off along the axis we came in on
    OVER = "over"  # above a reference, approaching downward
    ARC = "arc"  # swing about a hinge axis (articulated objects)
    HOLD = "hold"  # stay put; used to let the scene settle
    SET_GRIPPER = "set_gripper"  # pure actuation, no motion


#: Primitives that move nothing and therefore cost no model call, for either
#: pipeline. Kept explicit so neither can be credited for them.
FREE_KINDS = (GoalKind.HOLD, GoalKind.SET_GRIPPER)

#: Primitives whose motion is confined to a manifold rather than free in
#: space. ARC is the case that matters: a gripper holding a door handle has to
#: stay on the hinge radius, and a controller that can only pick from a fixed
#: set of directions will cut the chord and tear the grip off.
#:
#: This property was NOT part of the original routing rule. It was added after
#: running the door task, where routing on tolerance alone sent the swings to
#: the coarse controller, the grip slipped on the first step, and the hybrid
#: ended up both less reliable and more expensive than the baseline. Precision
#: requirement is not the only thing that decides who can drive a subgoal.
CONSTRAINED_KINDS = (GoalKind.ARC,)


@dataclass
class Frame:
    """A reference frame attached to something in the scene.

    `normal` points *out* of the surface the thing sits on or against, so
    approaching means moving along `-normal`. For a shelf item that is the
    shelf face normal; for something on the floor it is +z.
    """

    origin: np.ndarray
    normal: np.ndarray
    extent: np.ndarray = field(default_factory=lambda: np.array([0.05, 0.05, 0.05]))
    up: np.ndarray = field(default_factory=lambda: np.array([0.0, 0.0, 1.0]))
    #: Only meaningful for ARC: the hinge axis direction.
    axis: np.ndarray = field(default_factory=lambda: np.array([0.0, 0.0, 1.0]))

    def __post_init__(self) -> None:
        self.origin = np.asarray(self.origin, dtype=np.float64).reshape(3)
        self.normal = _unit(self.normal)
        self.extent = np.asarray(self.extent, dtype=np.float64).reshape(3)
        self.up = _unit(self.up)
        self.axis = _unit(self.axis)

    def lateral(self) -> np.ndarray:
        return closing_for(self.normal, self.up)


def _unit(v) -> np.ndarray:
    v = np.asarray(v, dtype=np.float64).reshape(3)
    n = float(np.linalg.norm(v))
    return v / n if n > 1e-9 else np.array([1.0, 0.0, 0.0])


def closing_for(approach: np.ndarray, up: np.ndarray) -> np.ndarray:
    """A finger-closing axis perpendicular to the approach direction.

    The obvious choice, `cross(approach, up)`, collapses to zero whenever the
    gripper approaches along `up` -- which is exactly the case for an item
    lying on the floor or a release straight down into a basket. Falling back
    to a second reference axis keeps the frame well defined for any approach.
    """
    for reference in (up, np.array([1.0, 0.0, 0.0]), np.array([0.0, 1.0, 0.0])):
        c = np.cross(approach, reference)
        if float(np.linalg.norm(c)) > 1e-6:
            return _unit(c)
    return np.array([0.0, 1.0, 0.0])


@dataclass
class Subgoal:
    """One step of a plan."""

    name: str
    kind: GoalKind
    #: Key into the scene references resolved each tick, e.g. "target",
    #: "basket", "goal_site", "hinge". Unused by HOLD and SET_GRIPPER.
    ref: str = ""
    tolerance_mm: float = 40.0
    needs_pixels: bool = False
    gripper: float = GRIPPER_OPEN
    #: Primitive parameters: distance, height, angle_deg, radius, steps.
    params: dict[str, Any] = field(default_factory=dict)
    #: Where `tolerance_mm` came from: "planner", "env", or "default". Carried
    #: into the results JSON so a reader can see which numbers were measured.
    tolerance_source: str = "planner"

    @property
    def is_free(self) -> bool:
        return self.kind in FREE_KINDS

    @property
    def path_constrained(self) -> bool:
        """Is the motion confined to a manifold?

        Derived from the primitive, so the planner does not have to know about
        it, but overridable through `params["path_constrained"]` for a
        primitive whose constraint depends on the scene.
        """
        if "path_constrained" in self.params:
            return bool(self.params["path_constrained"])
        return self.kind in CONSTRAINED_KINDS

    @property
    def is_fine(self) -> bool:
        """Does this subgoal need a visuomotor controller servoing on pixels?

        Either because its tolerance is tighter than open-loop accuracy, or
        because the plan says so outright. `needs_pixels` is the primary
        signal: a handle grasp with a generous 17 mm tolerance still has to be
        servoed, because the handle's position is only known to within the
        localiser's error.
        """
        from .types import FINE_PRECISION_MM

        return self.needs_pixels or self.tolerance_mm <= FINE_PRECISION_MM

    @property
    def tolerance_m(self) -> float:
        return self.tolerance_mm / 1000.0

    def to_dict(self) -> dict:
        return {
            "name": self.name,
            "kind": self.kind.value,
            "ref": self.ref,
            "tolerance_mm": self.tolerance_mm,
            "needs_pixels": self.needs_pixels,
            "gripper": self.gripper,
            "params": dict(self.params),
            "tolerance_source": self.tolerance_source,
        }

    @classmethod
    def from_dict(cls, d: dict) -> "Subgoal":
        return cls(
            name=str(d["name"]),
            kind=GoalKind(d["kind"]),
            ref=str(d.get("ref", "")),
            tolerance_mm=float(d.get("tolerance_mm", 40.0)),
            needs_pixels=bool(d.get("needs_pixels", False)),
            gripper=float(d.get("gripper", GRIPPER_OPEN)),
            params=dict(d.get("params", {})),
            tolerance_source=str(d.get("tolerance_source", "planner")),
        )


@dataclass
class TaskPlan:
    subgoals: list[Subgoal]
    #: The instruction the plan was generated from, for the record.
    instruction: str = ""
    #: Scene references the plan expects to be resolvable.
    required_refs: tuple[str, ...] = ()

    def __post_init__(self) -> None:
        if not self.subgoals:
            raise ValueError("a plan needs at least one subgoal")
        refs = {sg.ref for sg in self.subgoals if sg.ref}
        self.required_refs = tuple(sorted(refs))

    def __len__(self) -> int:
        return len(self.subgoals)

    def __getitem__(self, i: int) -> Subgoal:
        return self.subgoals[i]

    def to_dict(self) -> dict:
        return {
            "instruction": self.instruction,
            "required_refs": list(self.required_refs),
            "subgoals": [sg.to_dict() for sg in self.subgoals],
        }

    @classmethod
    def from_dict(cls, d: dict) -> "TaskPlan":
        return cls(
            subgoals=[Subgoal.from_dict(x) for x in d["subgoals"]],
            instruction=str(d.get("instruction", "")),
        )


@dataclass
class TaskCapabilities:
    """Quantities the *environment* declares or the robot can measure.

    These replace hand-chosen tolerances. Each one has a real source:

      place_tolerance_m   the task's own success threshold. For PickToBasket
                          the environment literally sets
                          TARGET_POS_THRESH = 0.2, so there is no reason to
                          guess 0.06 as the first version of this code did.
      finger_length_m     from the gripper URDF.
      gripper_stroke_m    how far the fingers open; with the item width it
                          gives the real positional slack of a grasp.
      neighbour_gap_m     distance from the target to the nearest other item.
                          On a dense retail board this, not the gripper, is
                          what bounds the allowable error.
      item_width_m        the target's narrowest horizontal dimension.
    """

    place_tolerance_m: float = 0.2
    finger_length_m: float = 0.03
    gripper_stroke_m: float = 0.05
    neighbour_gap_m: float = 0.07
    item_width_m: float = 0.065

    def grasp_tolerance_m(self) -> float:
        """How far the gripper may be off and still get a clean grasp.

        Two independent limits, whichever binds first:
          * finger slack: half the difference between how wide the fingers
            open and how wide the item is;
          * clutter: half the gap to the neighbouring item, since closing on
            the midpoint is the last pose that does not touch it.
        """
        slack = max(0.0, self.gripper_stroke_m - self.item_width_m) / 2.0
        clutter = max(0.0, self.neighbour_gap_m - self.item_width_m) / 2.0
        return max(0.002, min(slack, clutter) if clutter > 0 else slack)

    def withdraw_tolerance_m(self) -> float:
        """Backing out only has to clear the neighbour."""
        return max(0.005, self.neighbour_gap_m / 2.0)

    def to_dict(self) -> dict:
        return {
            "place_tolerance_m": self.place_tolerance_m,
            "finger_length_m": self.finger_length_m,
            "gripper_stroke_m": self.gripper_stroke_m,
            "neighbour_gap_m": self.neighbour_gap_m,
            "item_width_m": self.item_width_m,
            "derived_grasp_tolerance_mm": self.grasp_tolerance_m() * 1000.0,
            "derived_withdraw_tolerance_mm": self.withdraw_tolerance_m() * 1000.0,
        }


def calibrate(plan: TaskPlan, caps: TaskCapabilities) -> TaskPlan:
    """Replace the planner's guessed tolerances with measured ones.

    The language model proposing a plan has no way to know the gripper stroke
    or the task's success threshold, so whatever tolerance it suggests is a
    guess. Where the environment supplies the real number, it wins, and
    `tolerance_source` records that it did.
    """
    out: list[Subgoal] = []
    for sg in plan.subgoals:
        if sg.kind is GoalKind.CONTACT:
            out.append(
                replace(
                    sg,
                    tolerance_mm=caps.grasp_tolerance_m() * 1000.0,
                    tolerance_source="env",
                )
            )
        elif sg.kind is GoalKind.OVER:
            out.append(
                replace(
                    sg,
                    tolerance_mm=caps.place_tolerance_m * 1000.0,
                    tolerance_source="env",
                )
            )
        elif sg.kind is GoalKind.WITHDRAW:
            out.append(
                replace(
                    sg,
                    tolerance_mm=caps.withdraw_tolerance_m() * 1000.0,
                    tolerance_source="env",
                )
            )
        elif sg.kind is GoalKind.STANDOFF:
            # A standoff only has to be close enough that the fine controller
            # can see the target; a fixed fraction of the standoff distance.
            d = float(sg.params.get("distance", 0.18))
            out.append(
                replace(
                    sg, tolerance_mm=max(20.0, d * 1000.0 * 0.25),
                    tolerance_source="env",
                )
            )
        else:
            out.append(sg)
    return TaskPlan(subgoals=out, instruction=plan.instruction)


def resolve(
    sg: Subgoal,
    refs: dict[str, Frame],
    *,
    tcp_position: np.ndarray,
    anchor: Optional[Waypoint],
    anchor_tcp: Optional[np.ndarray] = None,
    finger_length_m: float,
) -> Optional[Waypoint]:
    """Turn one subgoal into a target pose.

    `anchor` is the pose reached when this subgoal *began*, not the pose
    reached last tick. The relative primitives -- WITHDRAW and ARC -- must
    measure from a fixed origin, or their goal recedes by the same increment
    every tick and is never reached.

    Returns None for the free primitives, which the driver handles directly.
    Raises KeyError if the plan names a scene reference perception did not
    supply: better a loud failure than silently aiming at the origin.
    """
    if sg.kind in FREE_KINDS:
        return None

    tcp_position = np.asarray(tcp_position, dtype=np.float64).reshape(3)
    anchor_tcp = (
        tcp_position
        if anchor_tcp is None
        else np.asarray(anchor_tcp, dtype=np.float64).reshape(3)
    )

    if sg.kind is GoalKind.WITHDRAW:
        # Measured from where the previous subgoal actually ended up, so
        # upstream localisation error does not propagate into the retreat.
        origin = anchor.position if anchor else anchor_tcp
        axis = anchor.approach if anchor else np.array([1.0, 0.0, 0.0])
        d = float(sg.params.get("distance", 0.30))
        return Waypoint(
            position=origin - axis * d,
            approach=axis,
            closing=anchor.closing if anchor else np.array([0.0, 1.0, 0.0]),
            gripper=sg.gripper,
        )

    frame = refs[sg.ref]

    if sg.kind is GoalKind.STANDOFF:
        d = float(sg.params.get("distance", 0.18))
        approach = -frame.normal
        return Waypoint(
            position=frame.origin + frame.normal * d,
            approach=approach,
            closing=closing_for(approach, frame.up),
            gripper=sg.gripper,
        )

    if sg.kind is GoalKind.CONTACT:
        approach = -frame.normal
        depth = min(finger_length_m, float(np.max(frame.extent)) * 0.5)
        return Waypoint(
            position=frame.origin - approach * depth,
            approach=approach,
            closing=closing_for(approach, frame.up),
            gripper=sg.gripper,
        )

    if sg.kind is GoalKind.OVER:
        h = float(sg.params.get("height", 0.40))
        lateral = np.asarray(sg.params.get("offset", [0.0, 0.0, 0.0]), dtype=np.float64)
        return Waypoint(
            position=frame.origin + frame.up * h + lateral.reshape(3),
            approach=-frame.up,
            closing=frame.lateral(),
            gripper=sg.gripper,
        )

    if sg.kind is GoalKind.ARC:
        # Swing the gripper about a hinge: a point on the arc `angle_deg` from
        # where this subgoal started. Measuring from the anchor rather than the
        # live TCP is what makes the goal a fixed point the coarse controller
        # can actually converge on -- and it is what lets the same coarse
        # controller drive a door as drives a straight reach.
        angle = np.deg2rad(float(sg.params.get("angle_deg", 60.0)))
        pivot, axis = frame.origin, frame.axis
        rotated = _rotate(anchor_tcp - pivot, axis, angle)
        approach = _unit(
            _rotate(anchor.approach if anchor else -frame.normal, axis, angle)
        )
        return Waypoint(
            position=pivot + rotated,
            approach=approach,
            closing=closing_for(approach, frame.up),
            gripper=sg.gripper,
        )

    raise ValueError(f"unhandled goal kind {sg.kind}")


def _rotate(v: np.ndarray, axis: np.ndarray, angle: float) -> np.ndarray:
    """Rodrigues rotation."""
    v = np.asarray(v, dtype=np.float64).reshape(3)
    k = _unit(axis)
    return (
        v * np.cos(angle)
        + np.cross(k, v) * np.sin(angle)
        + k * np.dot(k, v) * (1.0 - np.cos(angle))
    )
